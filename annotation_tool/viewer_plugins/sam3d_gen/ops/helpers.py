def _pack_splat_buffer(data: SplatData) -> np.ndarray:
    """Pack splat attributes into the uint32 buffer layout expected by Viser."""
    num = int(data.centers.shape[0])
    cov_triu = data.covariances.reshape((-1, 9))[:, np.array([0, 1, 2, 4, 5, 8])]
    buffer = np.concatenate(
        [
            data.centers.astype(np.float32).view(np.uint8),
            np.zeros((num, 4), dtype=np.uint8),
            cov_triu.astype(np.float16).copy().view(np.uint8),
            colors_to_uint8(data.rgbs),
            colors_to_uint8(data.opacities),
        ],
        axis=-1,
    ).view(np.uint32)
    return buffer


def _downsample_splat_for_display(
    splat: SplatData, *, max_points: int, seed: int, sample_mode: str = "opacity"
) -> SplatData:
    """Reduce splat point count for viewport performance."""
    n = int(splat.centers.shape[0])
    if max_points <= 0 or n <= max_points:
        return splat
    k = int(max_points)
    mode = str(sample_mode).strip().lower()
    if mode == "random":
        rng = np.random.default_rng(int(seed))
        idx = rng.choice(n, size=k, replace=False)
    else:
        weights = np.asarray(splat.opacities, dtype=np.float32).reshape(-1)
        if weights.shape[0] != n:
            weights = np.ones((n,), dtype=np.float32)
        idx = np.argpartition(weights, -k)[-k:]
    idx = np.asarray(idx, dtype=np.int64)
    return SplatData(
        centers=splat.centers[idx],
        rgbs=splat.rgbs[idx],
        opacities=splat.opacities[idx],
        covariances=splat.covariances[idx],
        scales=splat.scales[idx],
        rotations=splat.rotations[idx],
        sh=splat.sh[idx],
        opacity_raw=splat.opacity_raw[idx],
        centers_raw=splat.centers_raw[idx],
    )


def _apply_uniform_scale_about_center(splat: SplatData, scale: float) -> SplatData:
    """Uniformly scale a splat cloud about its opacity-weighted center."""
    s = float(scale)
    if abs(s - 1.0) < 1e-6:
        return splat
    centers = splat.centers.astype(np.float32, copy=False)
    w = splat.opacities.reshape(-1).astype(np.float32, copy=False)
    w = np.clip(w, 0.0, None) + 1e-6
    center = (centers * w[:, None]).sum(axis=0) / float(w.sum())

    centers_new = (centers - center[None, :]) * s + center[None, :]
    cov_new = splat.covariances.astype(np.float32, copy=False) * (s * s)
    scales_new = splat.scales.astype(np.float32, copy=False) * s
    try:
        centers_raw = splat.centers_raw.astype(np.float32, copy=False)
        centers_raw_new = (centers_raw - center[None, :]) * s + center[None, :]
    except Exception:
        centers_raw_new = centers_new

    return SplatData(
        centers=centers_new.astype(np.float32, copy=False),
        rgbs=splat.rgbs.astype(np.float32, copy=False),
        opacities=splat.opacities.astype(np.float32, copy=False),
        covariances=cov_new.astype(np.float32, copy=False),
        scales=scales_new.astype(np.float32, copy=False),
        rotations=splat.rotations.astype(np.float32, copy=False),
        sh=splat.sh.astype(np.float32, copy=False),
        opacity_raw=splat.opacity_raw.astype(np.float32, copy=False),
        centers_raw=centers_raw_new.astype(np.float32, copy=False),
    )


def _pad_rgb_to_square(
    image: np.ndarray, *, pad_value: int = 0
) -> tuple[np.ndarray, tuple[int, int, int, int]]:
    """Pad an RGB uint8 image to square by adding borders.

    Returns:
        Tuple of (padded_image, (pad_top, pad_bottom, pad_left, pad_right))
    """
    h, w = image.shape[:2]
    if h == w:
        return image, (0, 0, 0, 0)
    size = max(h, w)
    pad_top = (size - h) // 2 if h < size else 0
    pad_bottom = size - h - pad_top if h < size else 0
    pad_left = (size - w) // 2 if w < size else 0
    pad_right = size - w - pad_left if w < size else 0
    pad_val = int(np.clip(pad_value, 0, 255))
    out = np.full((size, size, 3), pad_val, dtype=image.dtype)
    out[pad_top : pad_top + h, pad_left : pad_left + w] = image
    return out, (pad_top, pad_bottom, pad_left, pad_right)


def _pad_alpha_to_square(
    alpha: np.ndarray, *, pad_value: int = 0
) -> tuple[np.ndarray, tuple[int, int, int, int]]:
    """Pad an alpha channel to square by adding borders.

    Returns:
        Tuple of (padded_alpha, (pad_top, pad_bottom, pad_left, pad_right))
    """
    h, w = alpha.shape[:2]
    if h == w:
        return alpha, (0, 0, 0, 0)
    size = max(h, w)
    pad_top = (size - h) // 2 if h < size else 0
    pad_bottom = size - h - pad_top if h < size else 0
    pad_left = (size - w) // 2 if w < size else 0
    pad_right = size - w - pad_left if w < size else 0
    pad_val = int(np.clip(pad_value, 0, 255))
    out = np.full((size, size), pad_val, dtype=alpha.dtype)
    out[pad_top : pad_top + h, pad_left : pad_left + w] = alpha
    return out, (pad_top, pad_bottom, pad_left, pad_right)


def _load_rgb_alpha_u8(image_path: Path, *, flip_udlr: bool) -> tuple[np.ndarray, np.ndarray | None]:
    """Load RGB and optional alpha (uint8) from image file.

    Args:
        image_path: Path to the image file
        flip_udlr: If True, flip image both horizontally and vertically

    Returns:
        Tuple of (rgb_array, alpha_array_or_none)
    """
    img = Image.open(image_path)
    if flip_udlr:
        img = img.transpose(Image.FLIP_LEFT_RIGHT).transpose(Image.FLIP_TOP_BOTTOM)
    if img.mode in ("RGBA", "LA") or ("A" in img.getbands()):
        rgba = np.array(img.convert("RGBA"), dtype=np.uint8)
        rgb = rgba[:, :, :3].astype(np.float32)
        alpha = rgba[:, :, 3].astype(np.float32) / 255.0
        rgb = rgb * alpha[..., None] + 255.0 * (1.0 - alpha[..., None])
        return np.clip(rgb, 0, 255).astype(np.uint8), rgba[:, :, 3].astype(np.uint8)
    rgb = np.array(img.convert("RGB"), dtype=np.uint8)
    return rgb, None


def _fill_vertices_from_gaussians(
    vertices: np.ndarray,
    *,
    centers_src: np.ndarray,
    rotations_src_wxyz: np.ndarray,
    scales_src_log: np.ndarray,
    opacity_raw: np.ndarray,
    sh_dc: np.ndarray,
) -> None:
    """Fill PLY vertex data from Gaussian parameters.

    Modifies vertices array in-place.
    """
    names = set(vertices.dtype.names or [])
    if not {"x", "y", "z"}.issubset(names):
        raise ValueError("PLY vertices missing required position fields (x,y,z)")
    vertices["x"] = centers_src[:, 0]
    vertices["y"] = centers_src[:, 1]
    vertices["z"] = centers_src[:, 2]

    if "opacity" in names:
        vertices["opacity"] = opacity_raw.reshape(-1).astype(np.float32)
    if "scale_0" in names and "scale_1" in names and "scale_2" in names:
        vertices["scale_0"] = scales_src_log[:, 0]
        vertices["scale_1"] = scales_src_log[:, 1]
        vertices["scale_2"] = scales_src_log[:, 2]
    if {"rot_0", "rot_1", "rot_2", "rot_3"}.issubset(names):
        vertices["rot_0"] = rotations_src_wxyz[:, 0]
        vertices["rot_1"] = rotations_src_wxyz[:, 1]
        vertices["rot_2"] = rotations_src_wxyz[:, 2]
        vertices["rot_3"] = rotations_src_wxyz[:, 3]
    if {"f_dc_0", "f_dc_1", "f_dc_2"}.issubset(names):
        vertices["f_dc_0"] = sh_dc[:, 0]
        vertices["f_dc_1"] = sh_dc[:, 1]
        vertices["f_dc_2"] = sh_dc[:, 2]


def _overlay_mask_and_points(
    image_rgb_u8: np.ndarray,
    *,
    masks: list[tuple[np.ndarray, tuple[int, int, int]]],
    points_xy: list[tuple[int, int, int]],
    eraser_circle: Optional[tuple[int, int, int]] = None,
    alpha: float = 0.45,
) -> np.ndarray:
    """Overlay segmentation masks and annotation points on an image.

    Args:
        image_rgb_u8: Base RGB image as uint8 array
        masks: List of (mask_array, color_tuple) pairs
        points_xy: List of (x, y, label) tuples where label=1 is positive
        eraser_circle: Optional (cx, cy, radius) for eraser visualization
        alpha: Blend alpha for mask overlay

    Returns:
        Composite image with masks and points overlaid
    """
    img = image_rgb_u8.copy()
    if img.dtype != np.uint8:
        img = np.clip(img, 0, 255).astype(np.uint8)

    if masks:
        img_f = img.astype(np.float32)
        for mask, color in masks:
            if mask is None:
                continue
            color_arr = np.array(color, dtype=np.float32).reshape(1, 1, 3)
            mask3 = mask[..., None].astype(np.float32)
            img_f = img_f * (1.0 - alpha * mask3) + color_arr * (alpha * mask3)
        img = np.clip(img_f, 0, 255).astype(np.uint8)

    pil = Image.fromarray(img)
    draw = ImageDraw.Draw(pil)
    for x, y, label in points_xy:
        r = 6
        color = (255, 0, 0) if label == 1 else (0, 128, 255)
        draw.ellipse((x - r, y - r, x + r, y + r), fill=color, outline=(255, 255, 255), width=2)
    if eraser_circle is not None:
        cx, cy, rad = eraser_circle
        draw.ellipse((cx - rad, cy - rad, cx + rad, cy + rad), outline=(255, 255, 255), width=3)
    return np.array(pil)
