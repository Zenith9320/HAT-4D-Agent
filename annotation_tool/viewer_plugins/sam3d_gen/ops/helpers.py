def _repo_root() -> Path:
    """Get the repository root path."""
    # ops/helpers.py -> ops -> sam3d_gen -> viewer_plugins -> repo root
    return Path(__file__).resolve().parents[4]


def _sam3d_repo_root() -> Path:
    """Get the SAM3D third-party repository path."""
    return Path(__file__).resolve().parents[1] / "thirdparty" / "sam-3d-objects"


def _ensure_sam3d_thirdparty_on_path() -> None:
    """Configure environment and Python path for SAM3D imports.

    Sets LIDRA_SKIP_INIT and CUDA_HOME environment variables, and adds
    SAM3D and segment-anything to sys.path if they exist.
    """
    # sam-3d-objects' sam3d_objects/__init__.py imports `sam3d_objects.init` unless this is set.
    # The vendored copy here doesn't ship that module; the official viser app sets this env var too.
    os.environ.setdefault("LIDRA_SKIP_INIT", "true")
    # Some torch extensions expect CUDA_HOME; sam-3d-objects' viser app sets CUDA_HOME=CONDA_PREFIX.
    if "CUDA_HOME" not in os.environ and "CONDA_PREFIX" in os.environ:
        os.environ["CUDA_HOME"] = os.environ["CONDA_PREFIX"]

    root = _sam3d_repo_root()
    if not root.exists():
        return
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))
    seg_any = root / "thirdparty" / "segment-anything"
    if seg_any.exists() and str(seg_any) not in sys.path:
        sys.path.insert(0, str(seg_any))


def _logit(p: np.ndarray, eps: float = 1e-6) -> np.ndarray:
    """Apply logit transformation to probability values."""
    p = np.clip(p, eps, 1.0 - eps)
    return np.log(p / (1.0 - p)).astype(np.float32)


def _default_ply_header_lines(vertex_count: int) -> list[bytes]:
    """Generate minimal PLY file header for Gaussian splatting.

    Compatible with `utils.ply_utils.load_splat_from_ply`.
    """
    n = int(vertex_count)
    lines = [
        "ply\n",
        "format binary_little_endian 1.0\n",
        "comment Generated by 4DGsEditor SAM3D Gen\n",
        f"element vertex {n}\n",
        "property float x\n",
        "property float y\n",
        "property float z\n",
        "property float f_dc_0\n",
        "property float f_dc_1\n",
        "property float f_dc_2\n",
        "property float opacity\n",
        "property float scale_0\n",
        "property float scale_1\n",
        "property float scale_2\n",
        "property float rot_0\n",
        "property float rot_1\n",
        "property float rot_2\n",
        "property float rot_3\n",
        "end_header\n",
    ]
    return [l.encode("ascii") for l in lines]


