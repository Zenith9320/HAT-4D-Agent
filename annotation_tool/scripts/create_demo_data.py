#!/usr/bin/env python3
"""Generate a tiny deterministic image and Gaussian sequence for local checks."""

from __future__ import annotations

import argparse
import json
import math
import shutil
import sys
from pathlib import Path
from typing import Sequence

import imageio.v3 as iio
import numpy as np


TOOL_ROOT = Path(__file__).resolve().parents[1]
SH_C0 = 0.28209479177387814
PLY_PROPERTIES = (
    "x",
    "y",
    "z",
    "f_dc_0",
    "f_dc_1",
    "f_dc_2",
    "opacity",
    "scale_0",
    "scale_1",
    "scale_2",
    "rot_0",
    "rot_1",
    "rot_2",
    "rot_3",
)


def _prepare_output(output_dir: Path, force: bool) -> Path:
    output_dir = output_dir.expanduser().resolve()
    protected = {Path("/"), Path.home().resolve(), TOOL_ROOT.resolve(), TOOL_ROOT.parent.resolve()}
    if output_dir in protected:
        raise ValueError(f"refusing to use protected output directory: {output_dir}")
    if output_dir.exists() and any(output_dir.iterdir()):
        if not force:
            raise ValueError(f"output directory is not empty; pass --force to replace it: {output_dir}")
        shutil.rmtree(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    return output_dir


def _demo_image(frame_index: int) -> np.ndarray:
    yy, xx = np.mgrid[0:64, 0:64]
    image = np.empty((64, 64, 3), dtype=np.uint8)
    image[..., 0] = (xx * 3 + frame_index * 17) % 256
    image[..., 1] = (yy * 3 + 48) % 256
    image[..., 2] = ((xx + yy) * 2 + 80) % 256
    center_x = 18 + frame_index * 6
    mask = (xx - center_x) ** 2 + (yy - 32) ** 2 <= 11**2
    image[mask] = np.array([240, 70, 45], dtype=np.uint8)
    return image


def _gaussian_rows(frame_index: int) -> np.ndarray:
    rows = []
    for latitude in range(6):
        phi = math.pi * (latitude + 0.5) / 6.0
        for longitude in range(8):
            theta = 2.0 * math.pi * longitude / 8.0
            radius = 0.42 + 0.02 * math.sin(theta * 2.0 + frame_index * 0.3)
            x = radius * math.sin(phi) * math.cos(theta) + frame_index * 0.025
            y = radius * math.cos(phi)
            z = radius * math.sin(phi) * math.sin(theta)
            rgb = np.array(
                [
                    0.35 + 0.45 * longitude / 7.0,
                    0.25 + 0.55 * latitude / 5.0,
                    0.65,
                ],
                dtype=np.float64,
            )
            sh = (rgb - 0.5) / SH_C0
            rows.append(
                [
                    x,
                    y,
                    z,
                    *sh.tolist(),
                    3.0,
                    -3.15,
                    -3.15,
                    -3.15,
                    1.0,
                    0.0,
                    0.0,
                    0.0,
                ]
            )
    return np.asarray(rows, dtype=np.float32)


def _write_ascii_ply(path: Path, rows: np.ndarray) -> None:
    header = [
        "ply",
        "format ascii 1.0",
        "comment generated by HAT-4D annotation demo",
        f"element vertex {len(rows)}",
        *[f"property float {name}" for name in PLY_PROPERTIES],
        "end_header",
    ]
    body = [" ".join(f"{float(value):.8g}" for value in row) for row in rows]
    path.write_text("\n".join([*header, *body, ""]), encoding="ascii")


def create_demo_data(output_dir: Path, frame_count: int = 3, force: bool = False) -> dict[str, object]:
    if frame_count < 1 or frame_count > 100:
        raise ValueError("frame_count must be between 1 and 100")
    output_dir = _prepare_output(Path(output_dir), force=force)
    input_dir = output_dir / "input"
    gs_dir = output_dir / "gs"
    eval_dir = output_dir / "eval_gt"
    input_dir.mkdir()
    gs_dir.mkdir()
    eval_dir.mkdir()

    frame_tokens = [f"{index:06d}" for index in range(frame_count)]
    for index, token in enumerate(frame_tokens):
        iio.imwrite(input_dir / f"{token}.png", _demo_image(index))
        _write_ascii_ply(gs_dir / f"{token}.ply", _gaussian_rows(index))

    metadata: dict[str, object] = {
        "format_version": 1,
        "frame_tokens": frame_tokens,
        "input_dir": "input",
        "gs_dir": "gs",
        "eval_gt_dir": "eval_gt",
    }
    (output_dir / "demo.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    return metadata


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output_dir", type=Path)
    parser.add_argument("--frame-count", type=int, default=3)
    parser.add_argument("--force", action="store_true", help="Replace a non-empty output directory.")
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    metadata = create_demo_data(args.output_dir, frame_count=args.frame_count, force=args.force)
    print(json.dumps(metadata, indent=2))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as exc:
        print(f"demo generation failed: {exc}", file=sys.stderr)
        raise SystemExit(2) from exc
